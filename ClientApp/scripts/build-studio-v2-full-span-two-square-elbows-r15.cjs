// Studio V2 r14 -> isolated r15. The full right-to-left EMPTY SMALL-PALLET
// return already belongs to the immutable 108-pallet main route. Its two
// RIGHT-ANGLE turns must be physical, not a visually disconnected straight.
// Keep the separate robot-local HALF-LENGTH red return added in r14 unchanged.
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const source=path.resolve(process.argv[2]||path.join(root,'.tmp-studio-v2-r14-db-readback.json'));
const output=path.resolve(process.argv[3]||path.join(root,'.tmp-studio-v2-full-span-square-elbows-r15-candidate.json'));
assert(source!==output&&!fs.existsSync(output),'Never overwrite previous snapshots or candidates');
const raw=fs.readFileSync(source,'utf8');
assert.equal(crypto.createHash('sha256').update(raw,'utf16le').digest('hex').toUpperCase(),
  '38334FB421D0BF55BC6590988D298EDC9E5BBA34106ADBAE99877680F8B47B74',
  'SQL Studio V2 r14 was updated; abort');
const m=JSON.parse(raw);
assert.equal(m.sceneId.toLowerCase(),'d7c2dfdf-39bf-4e69-a2c4-587cfaf63c94');
assert.equal(m.objects.length,58);
assert.equal(m.connections.length,54);
const obj=id=>{const o=m.objects.find(v=>v.objectId===id);assert(o,'Missing '+id);return o};
const spanId='reference-conveyor-ref-empty-return-merge';
const rightId='reference-conveyor-ref-empty-return-down';
const leftId='reference-conveyor-ref-return-edge-outer-down';
const mergeId='reference-gantry-merger';
const span=obj(spanId),right=obj(rightId),left=obj(leftId),merger=obj(mergeId);
const main=m.routes.find(r=>r.routeId==='component-route-d045206d');
const local=m.routes.find(r=>r.routeId==='studio-v2-surplus-silk-bidirectional-handoff');
assert(main?.points.length===42&&main.edges.length===46);
assert(local?.points.length===7&&local.edges.length===6);
const preservedMain=JSON.stringify(main),preservedLocal=JSON.stringify(local);
assert.equal(span.component.componentType,'roller-conveyor');
assert.equal(right.component.componentType,'roller-conveyor');
assert.equal(left.component.componentType,'roller-conveyor');
assert.equal(merger.component.componentType,'merger-conveyor');
assert.deepEqual(right.transform.position,[10.8,0,7.9]);
assert.deepEqual(span.transform.position,[-1.8999999999999995,0,9]);
assert.deepEqual(left.transform.position,[-14.6,0,12.1]);
assert(Math.abs(span.component.properties.length-25.4)<1e-8);
assert(Math.abs(right.component.properties.length-2.2)<1e-8);
assert(Math.abs(left.component.properties.length-6.2)<1e-8);
const pts=Object.fromEntries(main.points.map(p=>[p.pointId,p.position]));
assert.deepEqual(pts['ref-empty-return-diverter'],[10.8,.9,6.8]);
assert.deepEqual(pts['ref-empty-return-turn-b'],[10.8,.9,9]);
assert.deepEqual(pts['ref-gantry-merger'],[-14.6,.9,9]);
assert.deepEqual(pts['ref-return-outer-bottom'],[-14.6,.9,15.2]);
const required=[
  ['ref-empty-return-down','ref-empty-return-diverter','ref-empty-return-turn-b',rightId],
  ['ref-empty-return-merge','ref-empty-return-turn-b','ref-gantry-merger',spanId],
  ['ref-return-edge-outer-down','ref-gantry-merger','ref-return-outer-bottom',leftId],
];
for(const [edgeId,from,to,component] of required) {
 const edge=main.edges.find(e=>e.edgeId===edgeId);
 assert(edge&&edge.fromPointId===from&&edge.toPointId===to&&edge.componentObjectId===component);
}
assert(!span.component.properties.fullSpanTwoSquareElbows);
assert(!merger.component.properties.emptyReturnSquareThirdInput);
span.component.properties.fullSpanTwoSquareElbows=true;
span.component.properties.squareCornerSequence='right-down-west-left-down';
span.component.properties.emptySmallPalletOnly=true;
merger.component.properties.emptyReturnSquareThirdInput=true;
const rightLink=m.connections.find(c=>
 c.from.objectId===rightId&&c.from.portId==='output'&&c.to.objectId===spanId&&c.to.portId==='input');
assert(rightLink,'Expected existing physical right vertical-to-straight link');
rightLink.to.portId='square-right-input';
rightLink.metadata={...(rightLink.metadata||{}),physicalSquareCorner:true,angleDegrees:90,
 fromDirection:'south',toDirection:'west',emptySmallPalletOnly:true};
assert(!m.connections.some(c=>c.from.objectId===spanId&&c.to.objectId===mergeId));
m.connections.push({
 connectionId:'studio-v2-full-return-left-square-to-gantry-merger',
 from:{objectId:spanId,portId:'output'},
 to:{objectId:mergeId,portId:'empty-return-square-input'},
 autoGenerated:false,
 metadata:{physicalSquareCorner:true,angleDegrees:90,
   fromDirection:'west',toDirection:'south',
   emptySmallPalletOnly:true,requiresOccupancyGrant:true},
});
// No extra long roller, no route edge rewrite, no new local cache branch.
assert.equal(m.objects.length,58);
assert.equal(m.connections.length,55);
assert.equal(JSON.stringify(main),preservedMain);
assert.equal(JSON.stringify(local),preservedLocal);
const blue=obj('reference-conveyor-ref-edge-loaded-upper-right-in');
const red=obj('studio-v2-surplus-silk-empty-return-roller');
assert(Math.abs(Number(red.component.properties.length)-Number(blue.component.properties.length)/2)<1e-8);
assert.equal(m.runtime.routePalletInitializers.find(i=>i.routeId===main.routeId).simulationDefaultCount,108);
fs.writeFileSync(output,JSON.stringify(m,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({passed:true,sourceR14SqlVerified:true,
 sceneObjects:58,physicalConnections:55,
 fullEmptyReturn:{rightSquare:[10.8,9],horizontal:'25.4m west',
   leftSquare:[-14.6,9],leftExit:'south to z=15.2'},
 localRedHalfLengthUnchanged:true,main108GraphUntouched:true,
 robotBranchMainIdentityHandoff:'NOT VERIFIED',output},null,2));
